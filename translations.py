        if not ex.instructions_ua:
            ex.instructions_ua = f"НАЛАШТУВАННЯ:\n{ex.setup_ua}\n\nВИКОНАННЯ:\n{ex.execution_ua}\n\nПОРАДА ТРЕНЕРА:\n{ex.form_tips_ua or ''}"
