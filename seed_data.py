def tag_and_finalize_exercises(catalog):
    """Enriches and auto-tags all exercises with joint stresses, location flags, TRX anchor types, and equipment alternatives."""
    for ex in catalog:
        # Gender priority defaults
        if not hasattr(ex, "gender_priority") or not ex.gender_priority:
            ex.gender_priority = ["female", "male"]

        # Tag female sculpt prioritization
        n = (ex.name + " " + ex.id).lower()
        if any(w in n for w in [
            "hip thrust", "glute bridge", "abduction", "clamshell", "fire hydrant",
            "monster walk", "kickback", "plie", "sumo", "inner thigh", "adductor",
            "dead bug", "pallof", "waist", "calf raise", "towel slide", "side plank",
            "reverse crunch", "hip dips", "curtsy"
        ]):
            if "female" not in ex.gender_priority:
                ex.gender_priority.append("female")

        # Tag male hypertrophy prioritization
        if any(w in n for w in [
            "bench press", "back squat", "deadlift", "bent-over row", "military press",
            "pull-up", "clean and press", "skull crusher", "barbell curl"
        ]) and "female" not in ex.id:
            if "male" not in ex.gender_priority:
                ex.gender_priority.append("male")

        # Strictly enforce location=["gym"] for commercial equipment
        eq_lowers = [eq.lower() for eq in ex.equipment_needed]
        if any(any(m in eq for m in ["machine", "cable", "barbell", "smith", "rack", "pulldown", "press machine"]) for eq in eq_lowers):
            ex.location = ["gym"]
        # Reclassify mobility
        if ex.id in ["stick_thoracic_rotations", "banded_hip_distraction", "stick_overhead_good_morning", "stick_hinge_patterning"]:
            ex.movement_pattern = "Mobility"

        # Check floor/supine/prone foot-cradle TRX exercises that strictly require overhead bar anchor
        n = ex.name.lower()
        if any("trx" in eq.lower() for eq in ex.equipment_needed) or "trx" in ex.id:
            if any(w in n or w in ex.id for w in ["saw", "tuck", "pike", "hamstring", "cradle", "atomic", "hip_press", "hip press", "suspended_lunge", "suspended lunge", "pull-up", "inverted row", "pendulum"]):
                ex.trx_anchor = "bar"
            elif ex.trx_anchor in ["any", "door"]:
                ex.trx_anchor = "door"

        if not ex.joint_stress:
            stresses = set()
            p = ex.movement_pattern.lower()
            f = ex.exercise_family.lower()

            if p in ["squat", "lunge"] or "knee dominant" in f or any(w in n for w in ["squat", "lunge", "step-up", "pistol"]):
                stresses.add("knee")

            if any(w in n for w in ["push-up", "high plank", "bear crawl", "mountain climber"]) and "trx" not in n and "forearm" not in n:
                stresses.add("wrist")

            if "overhead" in n or "pike push-up" in n or "arnold" in n or "lateral raise" in n or "face pull" in n or "vertical push" in f or "shoulder isolation" in f or "posterior shoulder" in f:
                stresses.add("shoulder")

            if "bent-over row" in n or "good morning" in n or "deadlift" in n or "carry" in n or ("hip hinge" in f and ex.difficulty >= 3):
                stresses.add("lower_back")

            if "elbow flexion" in f or "elbow extension" in f or "curl" in n or "tricep" in n:
                stresses.add("elbow")

            if "jump" in n or "calf" in n or "pistol" in n:
                stresses.add("ankle")

            ex.joint_stress = sorted(list(stresses))

        if not ex.location:
            ex.location = ["home", "gym"]

        # Intelligent equipment alternatives if not explicitly defined
        if not getattr(ex, "equipment_alternatives", ""):
            eqs = [e.lower() for e in ex.equipment_needed]
            p = ex.movement_pattern.lower()
            if "adjustable dumbbells" in eqs or "barbell" in eqs:
                if "pull" in p:
                    ex.equipment_alternatives = "Long Resistance Band / TRX Inverted Row"
                    ex.equipment_alternatives_ua = "Гумова стрічка / Тяга в петлях TRX"
                elif "push" in p:
                    ex.equipment_alternatives = "Long Resistance Band / Floor Push-Up"
                    ex.equipment_alternatives_ua = "Гумова стрічка / Віджимання від підлоги"
                elif "squat" in p or "lunge" in p:
                    ex.equipment_alternatives = "Mini-Band / TRX Supported Squat"
                    ex.equipment_alternatives_ua = "Фітнес-резинка / Присідання з TRX"
                elif "hinge" in p:
                    ex.equipment_alternatives = "Long Band Good Morning / Slider Leg Curl"
                    ex.equipment_alternatives_ua = "Гудмонінг з гумою / Згинання на слайдерах"
                else:
                    ex.equipment_alternatives = "Resistance Band / Bodyweight"
                    ex.equipment_alternatives_ua = "Гумова стрічка / Власна вага"
            elif "trx" in eqs:
                if any(w in n for w in ["hamstring", "saw", "tuck", "pike"]):
                    ex.equipment_alternatives = "Towels / Sliders on Floor or Glute Bridge"
                    ex.equipment_alternatives_ua = "Рушники / Слайдери на підлозі або сідничний міст"
                elif "pull" in p:
                    ex.equipment_alternatives = "Dumbbell Bent-Over Row / Long Band Row"
                    ex.equipment_alternatives_ua = "Тяга гантелей у нахилі / Тяга з гумовою стрічкою"
                elif "push" in p:
                    ex.equipment_alternatives = "Dumbbell Floor Press / Push-Up"
                    ex.equipment_alternatives_ua = "Жим гантелей з підлоги / Віджимання"
                else:
                    ex.equipment_alternatives = "Adjustable Dumbbells / Resistance Band"
                    ex.equipment_alternatives_ua = "Гантелі / Гумова стрічка"
            elif "cable tower" in eqs or "lat pulldown machine" in eqs or "cable row machine" in eqs or "leg press" in eqs or "seated abduction machine" in eqs or "seated adduction machine" in eqs or "calf raise machine" in eqs:
                ex.equipment_alternatives = "Adjustable Dumbbells & Resistance Band"
                ex.equipment_alternatives_ua = "Гантелі та гумова стрічка"
            else:
                ex.equipment_alternatives = "Resistance Band / Bodyweight Tempo"
                ex.equipment_alternatives_ua = "Гумова стрічка / Робота з темпом"

    return catalog


